"""Generate Windows packaging metadata from the application version."""
from pathlib import Path
import runpy


def prepare(root):
    root = Path(root)
    version = runpy.run_path(str(root/'dsp408/version.py'))
    public, windows = version['VERSION'], version['WINDOWS_VERSION']
    folder = root/'packaging/windows'
    (folder/'version.iss').write_text('// Generated by tools/release_version.py\n#define AppVersion "'+public+'"\n', encoding='utf-8')
    (folder/'version_info.txt').write_text('''VSVersionInfo(
  ffi=FixedFileInfo(filevers=%s, prodvers=%s,
                   mask=0x3f, flags=0x0, OS=0x40004, fileType=0x1,
                   subtype=0x0, date=(0, 0)),
  kids=[StringFileInfo([StringTable('040904B0', [
    StringStruct('CompanyName', 'gremium.tech'),
    StringStruct('FileDescription', 'DSP408FIR Control'),
    StringStruct('FileVersion', '%s'),
    StringStruct('InternalName', 'DSP408FIR Control'),
    StringStruct('LegalCopyright', 'Copyright © 2026 Łukasz Białas · gremium.tech'),
    StringStruct('OriginalFilename', 'DSP408FIR Control.exe'),
    StringStruct('ProductName', 'DSP408FIR Control'),
    StringStruct('ProductVersion', '%s')
  ])]), VarFileInfo([VarStruct('Translation', [1033, 1200])])]
)
''' % (windows, windows, '.'.join(map(str,windows)), public), encoding='utf-8')


if __name__ == '__main__':
    prepare(Path(__file__).resolve().parents[1])
