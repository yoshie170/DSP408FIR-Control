"""Offline V1.12 .prs template import/export, preserving opaque vendor data.

Source header/body/trailer and numeric FIR layout audited in EXE. Original
opaque bytes are retained; coefficient edits use binary32 and fixed FF tails.
No transport, device requests, guessed defaults or firmware operations.
"""
from pathlib import Path
import math,struct
from dsp408.source_session import SourceDocument,project_state
from dsp408.source_bindings import plan_changes
from dsp408.source_codec import frame
from dsp408.model import DeviceModel

MAGIC=b'***FIR408V011***'
SIZE=67108
BODY_START=16
FIR_START=1570
FIR_END=67106
FILE_COMMANDS=frozenset((0x30,0x31,0x32,0x33,0x34,0x35,0x36,0x38,0x3A,0x3D,0x3E,0x3F,0x41,0x5B))

def fir_areas(state,bank,*,file_markers=True):
    """File/flash layout: four2048-word IN then eight1024-word OUT, binary32 LE.

    FFFFFFFF at word0 is the editor's identity/empty marker, never a NaN tap.
    Generated OUT coefficients are regenerated by4B, not read from these areas.
    """
    if len(bank)!=65536:raise ValueError('Complete FIR bank required')
    rows=SourceDocument(state).decoded()['channels'];result=[]
    for ch,row in enumerate(rows):
        offset=ch*8192 if ch<4 else 32768+(ch-4)*4096
        capacity=2048 if ch<4 else 1024
        count=row['fir_coefficient_count_raw'] if ch<4 else row['fir_tap_parameter_raw']
        external=ch<4 or row['fir_type_raw']==4
        area=bank[offset:offset+capacity*4];values=()
        if external and count and area[:4]!=b'\xff'*4:
            if not 1<=count<=capacity:raise ValueError(f'Invalid FIR count on channel {ch}')
            prefix=area[:count*4]
            if file_markers:
                #480C1C,4836A6/4839A5: noninitial FFFFFFFF becomes zero.
                prefix=b''.join(b'\0'*4 if prefix[i:i+4]==b'\xff'*4 else prefix[i:i+4] for i in range(0,len(prefix),4))
            values=struct.unpack('<'+str(count)+'f',prefix)
            if not all(math.isfinite(x) and x<=50 for x in values):raise ValueError(f'Invalid FIR coefficients on channel {ch}')
        result.append((offset,capacity,count,values))
    return result

def snapshot_bytes(state,bank):
    """Serializer47F1D8: active count in LE, FF tail; identity collapses to FF.

    Retain already erased areas. Do not serialize flash page padding as taps.
    """
    state,bank=bytes(state),bytes(bank)
    if len(state)!=1556 or len(bank)!=65536:raise ValueError('Complete1556-byte state and65536-byte FIR bank required')
    result=bytearray(bank)
    rows=SourceDocument(state).decoded()['channels']
    for ch,(offset,capacity,count,values) in enumerate(fir_areas(state,bank,file_markers=False)):
        if ch>=4 and rows[ch]['fir_type_raw']!=4:
            #4808DB..480A9E: generated designs serialize only two preview words.
            area=bank[offset:offset+8]
            if area[:4]==b'\xff'*4:values=()
            else:
                values=struct.unpack('<2f',area);count=2
                if not all(math.isfinite(x) and x<=50 for x in values):raise ValueError('Invalid output FIR preview words')
        data=b''
        if values:
            data=struct.pack('<'+str(count)+'f',*values)
            if values[0]==1.0 and all(x==0 for x in values[1:]):data=b''
        result[offset:offset+capacity*4]=data+b'\xff'*(capacity*4-len(data))
    return MAGIC+state[2:]+bytes(result)+b'\r\n'

def validate(raw):
    if len(raw)!=SIZE or raw[:16]!=MAGIC or raw[-2:]!=b'\r\n':
        raise ValueError('Unsupported PRS: expected original FIR408 V011 header,67108 bytes and CRLF trailer')
    return bytes(raw)

def document(raw):
    validate(raw)
    # .prs omits the opaque first2 bytes of the wire-state container. FF FF is
    # an internal decoder placeholder only; never serialized or sent as state.
    return SourceDocument(b'\xff\xff'+raw[BODY_START:FIR_START],
                          origin='PRS file body; opaque wire header absent, internal placeholder only')

def apply_file_packet(doc,raw):
    """File records are independent; temporarily remove native resolver masks.

    This edits bytes in a file only and must never be used as a device reducer.
    """
    from dsp408.channel_link import mask_offset,self_mask
    saved=[bytes(doc.data[mask_offset(i):mask_offset(i)+2]) for i in range(12)]
    try:
        for i in range(12):doc.data[mask_offset(i):mask_offset(i)+2]=self_mask(i).to_bytes(2,'little')
        doc.apply(raw)
    finally:
        for i in range(12):doc.data[mask_offset(i):mask_offset(i)+2]=saved[i]

def from_bytes(raw):
    raw=validate(raw)
    model,issues=project_state(document(raw),DeviceModel().to_dict(),strict=False)
    if issues:raise ValueError('PRS contains unrepresented settings: '+str(issues[:3]))
    for channel,(_,_,_,values) in zip(model.channels,fir_areas(bytes(document(raw).data),raw[FIR_START:FIR_END])):
        channel.fir.coefficients=list(values)
    model.vendor_prs_hex=raw.hex()
    model.validate()
    return model


def from_read_snapshot(state,bank):
    """Complete1556+65536 received read to original-format configuration/FIR."""
    state=bytes(state);bank=bytes(bank)
    if len(state)!=1556 or len(bank)!=65536:raise ValueError('PRS snapshot requires complete1556-byte state and65536-byte FIR bank')
    return from_bytes(snapshot_bytes(state,bank))

def load(path):
    with Path(path).open('rb') as stream:raw=stream.read(SIZE+1)
    return from_bytes(raw)

def to_bytes(model):
    model.validate()
    if not model.vendor_prs_hex:
        raise ValueError('PRS needs an original .prs template to preserve unknown settings and FIR banks. Load .prs first or save JSON.')
    raw=validate(bytes.fromhex(model.vendor_prs_hex))
    baseline=from_bytes(raw)
    before=baseline.to_dict();wanted=model.to_dict()
    # Display units and local paths do not belong to the vendor file.
    before['settings']['delay_unit']=wanted['settings']['delay_unit']
    for ch,(a,b) in enumerate(zip(before['inputs']+before['outputs'],wanted['inputs']+wanted['outputs'])):
        a['fir']['path']=b['fir']['path']
        # IN has no native design TYPE; our CSV loader uses External FIR as
        # presentation metadata. Coefficients/count and4F carry the real state.
        if ch<4 and b['fir']['mode'] in ('BYPASS','External FIR'):
            a['fir']['mode']=b['fir']['mode']
    doc=document(raw)
    bank=bytearray(raw[FIR_START:FIR_END])
    for ch,(a,b) in enumerate(zip(before['inputs']+before['outputs'],wanted['inputs']+wanted['outputs'])):
        if a['fir']['coefficients']!=b['fir']['coefficients']:
            values=b['fir']['coefficients'];offset=ch*8192 if ch<4 else 32768+(ch-4)*4096;capacity=2048 if ch<4 else 1024
            if values:
                from dsp408.source_codec import fir_chunks
                for payload in fir_chunks(ch,values):apply_file_packet(doc,frame(0x4E,payload))
                data=struct.pack('<'+str(len(values))+'f',*values)
                if not all(math.isfinite(x) and x<=50 for x in struct.unpack('<'+str(len(values))+'f',data)):raise ValueError('Invalid FIR binary32 coefficient')
                bank[offset:offset+capacity*4]=data+b'\xff'*(capacity*4-len(data))
            else:
                bank[offset:offset+capacity*4]=b'\xff'*(capacity*4)
            a['fir']['coefficients']=list(values)
    # The numeric writer updates count/type; seed its projected fields before
    # ordinary edits, so source co-fields are retained rather than guessed.
    projected,issues=project_state(doc,before,strict=False)
    if issues:raise ValueError('PRS FIR edit cannot be represented: '+str(issues[:3]))
    before=projected.to_dict()
    plan=plan_changes(before,wanted,raw_state=doc.decoded())
    excluded=[p.path for p in plan.packets if p.command not in FILE_COMMANDS|{0x4B,0x4C,0x4F}]
    if plan.blocked or plan.local_only or excluded:
        raise ValueError('PRS cannot represent these edits without replacing unverified data; save JSON: '+
                         str(plan.blocked+plan.local_only+excluded)[:700])
    for p in plan.packets:
        apply_file_packet(doc,frame(p.command,p.payload))
        if p.command==0x4B and p.payload[1]!=4:
            off=32768+(p.payload[0]-4)*4096;bank[off:off+4096]=b'\xff'*4096
    # File-only topology: independent records above have already been encoded.
    # Never send these raw RAM masks as a command or emulate firmware flash copy.
    from dsp408.channel_link import mask_offset,validate_group_state
    for ch,value in enumerate(model.link_masks()):
        at=mask_offset(ch);doc.data[at:at+2]=value.to_bytes(2,'little')
    validate_group_state(bytes(doc.data))
    from dsp408.fir_usb_import import resource_usage
    resource_usage(bytes(doc.data))  # Counts include the implicit FF identity.
    result=MAGIC+bytes(doc.data[2:])+bytes(bank)+b'\r\n'
    validate(result)
    return result

def save(model,path):
    raw=to_bytes(model)  # Validate all changes before touching the destination.
    from dsp408.atomic_file import write_bytes
    write_bytes(path,raw)
    # Commit the exact serialized template only after the atomic write.
    # Subsequent Clear retains the last saved count/co-fields, not an older
    # template's count from before the user's coefficient import.
    model.vendor_prs_hex=raw.hex()
